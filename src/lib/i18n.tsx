const DICTS: Record<Lang, Dict> = { en, th }

export type T = (key: Key, vars?: Record<string, string | number>) => string

export function makeT(lang: Lang): T {
  const d = DICTS[lang]
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
}

export const fmtNum = (n: number, lang: Lang) => n.toLocaleString(lang === 'th' ? 'th-TH' : 'en-US')

export function fmtDate(key: string, lang: Lang) {
  const [y, m, d] = key.split('-').map(Number)
  return new Date(y, m - 1, d).toLocaleDateString(lang === 'th' ? 'th-TH' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric' })
}

const LangCtx = createContext<{ lang: Lang; t: T }>({ lang: 'en', t: makeT('en') })
export const LangProvider = ({ lang, children }: { lang: Lang; children: ReactNode }) => (
  <LangCtx.Provider value={{ lang, t: makeT(lang) }}>{children}</LangCtx.Provider>
)
export const useT = () => useContext(LangCtx)
